'use strict';

/**
 * Builds public/js/icons.js: just the Lucide icons the app uses, as plain data
 * (no SVG files, no innerHTML — the page draws them with createElementNS).
 *
 * Icon names are collected from the sources:
 *   data-icon="…"           in public/index.html
 *   any '…' string literal  in public/js that is a Lucide icon name
 *                           (names are often picked at run time, e.g. 'eye' / 'eye-off')
 * A few extra icons may come along when an ordinary string happens to be an
 * icon name too — harmless, they're tiny.
 *
 * Usage (Lucide isn't a dependency — fetch it just for this):
 *   npm install --no-save lucide-static@1.49.0
 *   npm run icons
 */
const fs = require('node:fs');
const path = require('node:path');

const ROOT = path.join(__dirname, '..');
const OUTPUT = path.join(ROOT, 'public', 'js', 'icons.js');
const NODES = path.join(ROOT, 'node_modules', 'lucide-static', 'icon-nodes.json');
const PACKAGE = path.join(ROOT, 'node_modules', 'lucide-static', 'package.json');

function sourceFiles(dir) {
  return fs.readdirSync(dir, { withFileTypes: true }).flatMap((entry) => {
    const full = path.join(dir, entry.name);
    if (entry.isDirectory()) return sourceFiles(full);
    return /\.(html|js)$/.test(entry.name) && full !== OUTPUT ? [full] : [];
  });
}

/** Icon data from the SVG file — needed for names Lucide keeps only as aliases (e.g. trash-2). */
function nodesFromSvg(name) {
  const file = path.join(ROOT, 'node_modules', 'lucide-static', 'icons', `${name}.svg`);
  if (!fs.existsSync(file)) return null;
  const svg = fs.readFileSync(file, 'utf8');
  const nodes = [];
  for (const [, tag, attributes] of svg.matchAll(/<(path|circle|rect|line|polyline|polygon|ellipse)\s([^>]*?)\/?>/g)) {
    const attrs = {};
    for (const [, key, value] of attributes.matchAll(/([a-z-]+)="([^"]*)"/g)) attrs[key] = value;
    nodes.push([tag, attrs]);
  }
  return nodes.length ? nodes : null;
}

function usedIconNames(isIcon) {
  const required = new Set();
  const candidates = new Set();
  for (const file of sourceFiles(path.join(ROOT, 'public'))) {
    const text = fs.readFileSync(file, 'utf8');
    if (file.endsWith('.html')) for (const match of text.matchAll(/data-icon="([a-z0-9-]+)"/g)) required.add(match[1]);
    else for (const match of text.matchAll(/'([a-z0-9]+(?:-[a-z0-9]+)*)'/g)) candidates.add(match[1]);
  }
  return {
    required: [...required].sort(),
    found: [...candidates].filter(isIcon).sort(),
  };
}

function main() {
  if (!fs.existsSync(NODES)) {
    console.error('lucide-static is not installed. Run: npm install --no-save lucide-static@1.49.0');
    process.exit(1);
  }
  const nodes = JSON.parse(fs.readFileSync(NODES, 'utf8'));
  const { version } = JSON.parse(fs.readFileSync(PACKAGE, 'utf8'));
  const lookup = (name) => nodes[name] || nodesFromSvg(name);
  const { required, found } = usedIconNames((name) => Boolean(lookup(name)));
  const missing = required.filter((name) => !lookup(name));
  if (missing.length) {
    console.error(`Unknown Lucide icon(s) in index.html: ${missing.join(', ')}`);
    process.exit(1);
  }
  const names = [...new Set([...required, ...found])].sort();

  const body = names.map((name) => `    ${JSON.stringify(name)}: ${JSON.stringify(lookup(name))},`).join('\n');
  const output = `/**
 * Icons from Lucide v${version} (https://lucide.dev) — ISC License, see public/js/icons-LICENSE.txt.
 * Generated by scripts/build-icons.js; don't edit by hand (run \`npm run icons\`).
 * Each icon is a list of [tag, attributes] for a 24×24, stroke-based SVG.
 */
(function (root) {
  'use strict';
  root.PHIcons = Object.freeze({
${body}
  });
})(typeof self !== 'undefined' ? self : this);
`;
  fs.writeFileSync(OUTPUT, output);
  fs.copyFileSync(path.join(ROOT, 'node_modules', 'lucide-static', 'LICENSE'), path.join(ROOT, 'public', 'js', 'icons-LICENSE.txt'));
  console.log(`Wrote ${names.length} icons to ${path.relative(ROOT, OUTPUT)}`);
}

main();
